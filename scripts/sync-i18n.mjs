// frontend/src/lib/messages.js 의 번역 사전을 루트 index.html 의 인라인 스크립트에 동기화한다.
// 사용: node scripts/sync-i18n.mjs  (또는 npm run i18n:sync)
import { readFile, writeFile } from 'node:fs/promises'
import { DEFAULT_LANGUAGE, LANGUAGES, MESSAGES } from '../frontend/src/lib/messages.js'

const INDEX_FILE = new URL('../index.html', import.meta.url)
const START = '/* i18n:start (generated by scripts/sync-i18n.mjs; do not edit) */'
const END = '/* i18n:end */'

export function buildBlock() {
  // `</` 가 인라인 <script> 를 조기 종료하지 않도록 이스케이프한다.
  const json = (value) => JSON.stringify(value, null, 2).replaceAll('</', '<\\/')
  return [
    START,
    `const LANGUAGES = ${json(LANGUAGES)}`,
    `const DEFAULT_LANGUAGE = ${json(DEFAULT_LANGUAGE)}`,
    `const MESSAGES = ${json(MESSAGES)}`,
    END,
  ].join('\n')
}

export function applyBlock(html) {
  const a = html.indexOf(START)
  const b = html.indexOf(END)
  if (a === -1 || b === -1) throw new Error('index.html 에서 i18n 마커를 찾을 수 없습니다.')
  return html.slice(0, a) + buildBlock() + html.slice(b + END.length)
}

if (import.meta.url === new URL(process.argv[1], 'file://').href) {
  const html = await readFile(INDEX_FILE, 'utf8')
  await writeFile(INDEX_FILE, applyBlock(html))
  console.log('index.html 의 번역 사전을 갱신했습니다.')
}
